#!/usr/bin/env python3
"""Configure the range router (VMID 9200) entirely through the QEMU guest agent.

No network path to the router is used or needed: everything is pushed over the
guest-agent channel. Driven by segments.json (source of truth) and the
inter-segment allow-list. Idempotent: re-running overwrites config and reloads.

What it writes into the router:
  * /etc/systemd/network/10-seg-<name>.network  -- static gateway IP per segment
    NIC, matched by MAC so naming never matters; no default route (no egress).
  * /etc/dnsmasq.d/range.conf                    -- per-segment DHCP + local DNS,
    no upstream resolver (so guests cannot resolve internet names).
  * /etc/nftables.conf                           -- stateful firewall: default
    deny between segments + allow-list, router itself has no egress.
  * /etc/sysctl.d/99-router.conf                 -- ip_forward=1.

Run on the range host (vanilla):
    python3 configure_router.py [segments.json] [firewall-allow.rules]
Defaults look next to this script, token at ~/cathedral/pve-api-token.json.
"""
import base64
import json
import os
import shlex
import sys

_here = os.path.dirname(os.path.abspath(__file__))
# pve.py lives beside this file when deployed to ~/cathedral, or in the repo.
sys.path[:0] = [_here, os.path.join(_here, "..", "range-host"),
                os.path.expanduser("~/cathedral")]
from pve import Pve  # noqa: E402

ROUTER_VMID = 9200
TOKEN = os.path.expanduser("~/cathedral/pve-api-token.json")


def seg_mac(gateway_ip):
    b, c, d = (int(x) for x in gateway_ip.split(".")[1:])
    return "52:54:00:%02x:%02x:%02x" % (b, c, d)


def prefix(cidr):
    return cidr.split("/")[1]


def write_file(p, vmid, path, content):
    """Write a file inside the guest via the agent (no network needed)."""
    b64 = base64.b64encode(content.encode()).decode()
    cmd = f"install -D -m 0644 /dev/null {shlex.quote(path)} && " \
          f"printf %s {shlex.quote(b64)} | base64 -d > {shlex.quote(path)}"
    code, out, err = p.guest_exec(vmid, ["bash", "-c", cmd])
    if code != 0:
        raise RuntimeError(f"write {path}: {err or out}")


def run(p, vmid, *argv, check=True):
    code, out, err = p.guest_exec(vmid, list(argv))
    if check and code != 0:
        raise RuntimeError(f"{' '.join(argv)} -> {code}: {err or out}")
    return code, out, err


def networkd(segs):
    for s in segs:
        yield f"10-seg-{s['name']}.network", (
            "[Match]\n"
            f"MACAddress={seg_mac(s['gateway_ip'])}\n\n"
            "[Network]\n"
            f"Address={s['gateway_ip']}/{prefix(s['cidr'])}\n"
            "ConfigureWithoutCarrier=yes\n"
            "LinkLocalAddressing=no\n"
            "IPv6AcceptRA=no\n"
        )


def dnsmasq_conf(segs):
    L = ["# generated by configure_router.py from segments.json",
         "no-resolv",          # no upstream: guests cannot resolve internet names
         "no-hosts",
         "domain-needed",
         "bogus-priv",
         "bind-dynamic",       # bind only live segment NICs, pick up new ones
         "except-interface=lo",
         "log-dhcp", ""]
    for s in segs:
        t, net, gw, dom = s["name"], s["cidr"], s["gateway_ip"], s["domain"]
        L += [f"# --- {t} ({net}) ---",
              f"dhcp-range=set:{t},{s['dhcp_start']},{s['dhcp_end']},255.255.255.0,12h",
              f"dhcp-option=tag:{t},option:router,{gw}",
              f"dhcp-option=tag:{t},option:dns-server,{gw}",
              f"dhcp-option=tag:{t},option:domain-name,{dom}",
              f"domain={dom},{net}",
              f"host-record=router.{dom},{gw}", ""]
    return "\n".join(L) + "\n"


def parse_rules(path, by_name):
    """Translate the allow-list file into nft forward-chain accept lines."""
    lines = []
    if not os.path.exists(path):
        return lines
    for raw in open(path):
        raw = raw.split("#", 1)[0].strip()
        if not raw:
            continue
        parts = raw.split()
        if len(parts) < 3:
            raise RuntimeError(f"bad allow rule: {raw!r}")
        src, dst, proto = parts[0], parts[1], parts[2].lower()
        dport = parts[3] if len(parts) > 3 else "any"
        match = []
        if src != "any":
            match.append(f"ip saddr {by_name[src]['cidr']}")
        if dst != "any":
            match.append(f"ip daddr {by_name[dst]['cidr']}")
        if proto in ("tcp", "udp"):
            match.append(f"{proto} dport {dport}" if dport != "any" else f"ip protocol {proto}")
        elif proto == "icmp":
            match.append("ip protocol icmp")
        elif proto != "any":
            raise RuntimeError(f"bad proto in: {raw!r}")
        lines.append("        " + " ".join(match) +
                     f' counter accept comment "allow {raw}"')
    return lines


def nft_conf(allow_lines):
    allow = "\n".join(allow_lines) if allow_lines else \
        "        # (no inter-segment holes; edit firewall-allow.rules to add)"
    return f"""#!/usr/sbin/nft -f
# Range router firewall. Own table only (never flush ruleset).
# input : services the router offers on its segments (DHCP, DNS, ICMP).
# forward: inter-segment routing, DEFAULT DENY + allow-list.
# output: router has NO egress (drop) beyond replies and its own DHCP/DNS/ICMP.
table inet router
delete table inet router
table inet router {{
    chain input {{
        type filter hook input priority 0; policy drop;
        iif "lo" accept
        ct state established,related accept
        ct state invalid drop
        meta l4proto {{ icmp, ipv6-icmp }} accept
        udp dport {{ 67, 68 }} accept
        udp dport 53 accept
        tcp dport 53 accept
        counter drop
    }}
    chain forward {{
        type filter hook forward priority 0; policy drop;
        ct state established,related accept
        ct state invalid drop
{allow}
        counter drop comment "inter-segment default deny"
    }}
    chain output {{
        type filter hook output priority 0; policy drop;
        oif "lo" accept
        ct state established,related accept
        meta l4proto {{ icmp, ipv6-icmp }} accept
        udp sport {{ 67, 68 }} accept
        udp sport 53 accept
        tcp sport 53 accept
        counter drop
    }}
}}
"""


def main():
    seg_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(_here, "segments.json")
    rules_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(_here, "firewall-allow.rules")
    segs = json.load(open(seg_path))
    by_name = {s["name"]: s for s in segs}

    p = Pve(TOKEN)
    print(f"waiting for router {ROUTER_VMID} guest agent ...")
    print(f"  agent up ({p.wait_agent(ROUTER_VMID, 600):.0f}s)")

    for fname, content in networkd(segs):
        write_file(p, ROUTER_VMID, f"/etc/systemd/network/{fname}", content)
    write_file(p, ROUTER_VMID, "/etc/sysctl.d/99-router.conf", "net.ipv4.ip_forward=1\n")
    write_file(p, ROUTER_VMID, "/etc/dnsmasq.d/range.conf", dnsmasq_conf(segs))
    allow_lines = parse_rules(rules_path, by_name)
    write_file(p, ROUTER_VMID, "/etc/nftables.conf", nft_conf(allow_lines))

    # Apply, in order. Idempotent: each is a reload/restart to the written state.
    run(p, ROUTER_VMID, "sysctl", "--quiet", "--system")
    run(p, ROUTER_VMID, "systemctl", "restart", "systemd-networkd")
    run(p, ROUTER_VMID, "nft", "-f", "/etc/nftables.conf")
    run(p, ROUTER_VMID, "systemctl", "enable", "--now", "nftables")
    run(p, ROUTER_VMID, "systemctl", "restart", "dnsmasq")

    _, addrs, _ = run(p, ROUTER_VMID, "ip", "-br", "-4", "addr")
    print("router addresses:")
    for ln in addrs.strip().splitlines():
        print("  " + ln)
    print(f"allow-list rules applied: {len(allow_lines)}")
    print("configure_router.py done")


if __name__ == "__main__":
    main()
